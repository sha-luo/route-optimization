def solve_master_problem(network: Network):
    """
    Master problem for the column generation algorithm. This optimization aims to minimize the total traveling distance / cost that satisfies all the 
    edge level demand. Variable x_r is the number of times route r is carried out, with the routes being generated by the subproblem.

    Parameters:
    - network: Network object containing nodes, edges, and routes

    Returns:
    - result: Highs solver result object
    """

    
    model = pyo.ConcreteModel("master_problem")
    model.x = pyo.Var(network.routes, within=pyo.NonNegativeReals)
    model.obj = pyo.Objective(expr=sum(r.distance * model.x[r] for r in network.routes))
    
    # Print model components for debugging
    # print("Routes in network:", len(network.routes))
    # print("Edges in network:", len(network.edges))

    # print('Routes:')
    # for route in network.routes:
    #     print(route)

    def demand_constraint_rule(model, e):

        return sum(model.x[r] for r in network.edges[e].routes) >= network.edges[e].demand if network.edges[e].demand > 0 else pyo.Constraint.Skip
    
    model.flow_cons = pyo.Constraint(network.edges, rule=demand_constraint_rule)

    # print the full model
    # print('Full model:')
    # model.pprint()

    solver = Highs()
    result = solver.solve(model)

    optimal_value = pyo.value(model.obj)

     # Store optimization results in dictionary
    optimal_routes = {r: model.x[r].value for r in network.routes if model.x[r].value > 1e-6}


    # Print optimization results
    # print("\nOptimization Results:")
    # for r in network.routes:
