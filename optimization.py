def find_integer_solution(network: Network):
    """
    Integer version of the master problem for the column generation algorithm. This optimization aims to minimize 
    the total traveling distance / cost that satisfies all the edge level demand. Variable x_r is the integer 
    number of times route r is carried out.

    Parameters:
    - network: Network object containing nodes, edges, and routes

    Returns:
    - result: Highs solver result object
    """
    
    model = pyo.ConcreteModel("integer_master_problem")
    model.x = pyo.Var(network.routes, within=pyo.NonNegativeIntegers)
    model.obj = pyo.Objective(expr=sum(r.distance * model.x[r] for r in network.routes))
    
    def demand_constraint_rule(model, e):
        return sum(model.x[r] for r in network.edges[e].routes) >= network.edges[e].demand if network.edges[e].demand > 0 else pyo.Constraint.Skip
    
    model.flow_cons = pyo.Constraint(network.edges, rule=demand_constraint_rule)

    solver = Highs()
    result = solver.solve(model)

    optimal_value = pyo.value(model.obj)
    optimal_routes = {r: model.x[r].value for r in network.routes if model.x[r].value > 1e-6}
        
    return optimal_value, optimal_routes



def solve_subproblem(network: Network):
    """
    Finds the shortest cycle starting and ending at dc_0 using a modified Bellman-Ford algorithm
    with 2D matrices to track distances and predecessors at each step.
    """
    import math
    
    # Start from first DC (dc_0)
    start_dc = next(iter(network.dcs.values())).name
    
    # Get number of nodes and max steps
    n_nodes = len(network.nodes)
    max_steps = 10  # Maximum steps allowed in path
    
    # Create node to index mapping for matrix operations
    node_to_idx = {node.name: idx for idx, node in enumerate(network.nodes.values())}
    idx_to_node = {v: k for k, v in node_to_idx.items()}
    
    # Initialize 2D matrices for distances and predecessors
    distances = [[0] * (max_steps + 1) for _ in range(n_nodes)]
    reduced_costs = [[math.inf] * (max_steps + 1) for _ in range(n_nodes)]
    predecessors = [[None] * (max_steps + 1) for _ in range(n_nodes)]
    
    # Set initial distance for start_dc
    start_idx = node_to_idx[start_dc]
    reduced_costs[start_idx][0] = 0
    
    # Update reduced_cost, distances, predecessors step by step
    for t in range(max_steps):
        
        for u_idx in range(n_nodes):
            u = idx_to_node[u_idx]
            for e in network.nodes[u].outgoing_edges:
                v = e.destination
                v_idx = node_to_idx[v.name]
                reduced_cost = e.distance - e.dual_value 

                if reduced_costs[u_idx][t] + reduced_cost < reduced_costs[v_idx][t+1]:
                    reduced_costs[v_idx][t+1] = reduced_costs[u_idx][t] + reduced_cost
                    distances[v_idx][t+1] = distances[u_idx][t] + e.distance 
                    predecessors[v_idx][t+1] = u_idx
                # else:
                #     reduced_costs[v_idx][t+1] = reduced_costs[v_idx][t]
                #     distances[v_idx][t+1] = distances[v_idx][t]
                #     predecessors[v_idx][t+1] = v_idx

    # Find best cycle back to start_dc
    path = [start_dc]
    curr_idx = start_idx
    # check if there is a negative reduced cost cycle
    if reduced_costs[start_idx][max_steps] < -1e-6:
        # construct the cycle using predecessors
        for t in range(max_steps, 0, -1):
            curr_idx = predecessors[curr_idx][t]
            if idx_to_node[curr_idx] != path[-1]:
                path.append(idx_to_node[curr_idx])
        
        if path[0] == path[-1]:
            path.reverse()
            r = Route([network.nodes[n] for n in path])
            return r
    
    return None


